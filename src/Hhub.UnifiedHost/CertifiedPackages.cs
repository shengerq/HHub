using System.IO.Compression;
using System.Security.Cryptography;
using System.Security.Cryptography.Pkcs;
using System.Security.Cryptography.X509Certificates;
using System.Text.Json;
using Hhub.PluginContracts;

namespace Hhub.UnifiedHost;

public sealed record PackageFile(string Path, long Length, string Sha256);
public sealed record PackageInventory(int SchemaVersion, string PluginId, string Version, PackageFile[] Files);
public sealed record VerifiedPackage(PluginDefinition Definition, string Sha256, string SignerSha256, string ContentHash);

public sealed class CertificationPolicy(IEnumerable<string> trustedSigners, IEnumerable<string>? revokedPackages = null)
{
    private readonly HashSet<string> _trusted = new(trustedSigners, StringComparer.OrdinalIgnoreCase);
    private readonly HashSet<string> _revoked = new(revokedPackages ?? [], StringComparer.OrdinalIgnoreCase);
    public bool Trusts(string fingerprint) => _trusted.Contains(fingerprint);
    public bool Revoked(string packageHash) => _revoked.Contains(packageHash);
}

public static class CertifiedPackages
{
    public const string SignatureEntry = "certification.p7s";
    public const long MaxPackageBytes = 256L * 1024 * 1024;
    public const long MaxExpandedBytes = 512L * 1024 * 1024;

    public static VerifiedPackage Verify(string path, CertificationPolicy policy)
    {
        using var input = new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.Read);
        if (input.Length > MaxPackageBytes) throw new InvalidDataException("package.too-large");
        string hash = Convert.ToHexString(SHA256.HashData(input)); input.Position = 0;
        if (policy.Revoked(hash)) throw new InvalidDataException("package.revoked");
        using var archive = new ZipArchive(input, ZipArchiveMode.Read);
        var entries = Inspect(archive);
        if (!entries.TryGetValue(SignatureEntry, out var signature)) throw new InvalidDataException("package.not-certified");
        var cms = new SignedCms(); cms.Decode(Read(signature, 1024 * 1024));
        cms.CheckSignature(verifySignatureOnly: true);
        if (cms.SignerInfos.Count != 1 || cms.SignerInfos[0].DigestAlgorithm.Value != "2.16.840.1.101.3.4.2.1"
            || cms.SignerInfos[0].Certificate is not X509Certificate2 certificate)
            throw new InvalidDataException("package.signer-invalid");
        string fingerprint = certificate.GetCertHashString(HashAlgorithmName.SHA256);
        if (!policy.Trusts(fingerprint)) throw new InvalidDataException("package.signer-untrusted");
        string contentHash = Convert.ToHexString(SHA256.HashData(cms.ContentInfo.Content));
        if (policy.Revoked(contentHash)) throw new InvalidDataException("package.revoked");
        var inventory = PluginApi.Read<PackageInventory>(System.Text.Encoding.UTF8.GetString(cms.ContentInfo.Content));
        if (inventory.SchemaVersion != 1 || inventory.Files.Length != entries.Count - 1
            || inventory.Files.Select(item => item.Path).Distinct(StringComparer.OrdinalIgnoreCase).Count() != inventory.Files.Length)
            throw new InvalidDataException("package.inventory-invalid");
        foreach (var file in inventory.Files)
        {
            PluginApi.ValidatePath(file.Path);
            if (file.Path == SignatureEntry || !entries.TryGetValue(file.Path, out var entry) || entry.Length != file.Length)
                throw new InvalidDataException("package.inventory-mismatch");
            using var content = entry.Open();
            if (!string.Equals(Convert.ToHexString(SHA256.HashData(content)), file.Sha256, StringComparison.OrdinalIgnoreCase))
                throw new InvalidDataException("package.content-changed");
        }
        if (!entries.TryGetValue("plugin.json", out var manifestEntry)) throw new InvalidDataException("package.manifest-missing");
        var manifest = PluginApi.Read<PluginDefinition>(System.Text.Encoding.UTF8.GetString(Read(manifestEntry, 1024 * 1024)));
        PluginApi.Validate(manifest);
        if (inventory.PluginId != manifest.Id || inventory.Version != manifest.Version || !entries.ContainsKey(manifest.EntryPoint))
            throw new InvalidDataException("package.identity-mismatch");
        return new(manifest, hash, fingerprint, contentHash);
    }

    // Offline maintainer operation; no private key or trust is generated by the application.
    public static void CertifyDirectory(string source, string output, X509Certificate2 certificate)
    {
        if (!certificate.HasPrivateKey || DateTime.UtcNow < certificate.NotBefore.ToUniversalTime()
            || DateTime.UtcNow > certificate.NotAfter.ToUniversalTime()) throw new InvalidDataException("certificate.not-valid");
        string root = Path.GetFullPath(source);
        string target = Path.GetFullPath(output);
        if (target.StartsWith(root.TrimEnd(Path.DirectorySeparatorChar) + Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase))
            throw new InvalidDataException("package.output-inside-source");
        var manifest = PluginApi.Read<PluginDefinition>(File.ReadAllText(Path.Combine(root, "plugin.json")));
        PluginApi.Validate(manifest);
        _ = EnumeratePlainEntries(root);
        string temporary = target + "." + Guid.NewGuid().ToString("N") + ".tmp";
        try
        {
            ZipFile.CreateFromDirectory(root, temporary);
            using (var archive = ZipFile.Open(temporary, ZipArchiveMode.Update))
            {
                var entries = Inspect(archive);
                if (entries.ContainsKey(SignatureEntry) || !entries.ContainsKey(manifest.EntryPoint))
                    throw new InvalidDataException("package.source-invalid");
                var files = entries.Values.OrderBy(entry => entry.FullName, StringComparer.Ordinal).Select(entry =>
                {
                    long length = entry.Length;
                    using var content = entry.Open();
                    return new PackageFile(entry.FullName, length, Convert.ToHexString(SHA256.HashData(content)));
                }).ToArray();
                var inventory = new PackageInventory(1, manifest.Id, manifest.Version, files);
                var cms = new SignedCms(new ContentInfo(JsonSerializer.SerializeToUtf8Bytes(inventory, PluginApi.Json)), detached: false);
                cms.ComputeSignature(new CmsSigner(certificate) { DigestAlgorithm = new Oid("2.16.840.1.101.3.4.2.1") });
                using var destination = archive.CreateEntry(SignatureEntry).Open(); destination.Write(cms.Encode());
            }
            Verify(temporary, new CertificationPolicy([certificate.GetCertHashString(HashAlgorithmName.SHA256)]));
            File.Move(temporary, target, overwrite: false);
        }
        finally { if (File.Exists(temporary)) File.Delete(temporary); }
    }

    internal static string[] EnumeratePlainEntries(string root)
    {
        var result = new List<string>(); var pending = new Stack<string>(); pending.Push(root);
        while (pending.TryPop(out string? directory))
        {
            if ((File.GetAttributes(directory) & FileAttributes.ReparsePoint) != 0)
                throw new InvalidDataException("package.link-not-allowed");
            foreach (string path in Directory.EnumerateFileSystemEntries(directory))
            {
                var attributes = File.GetAttributes(path);
                if ((attributes & FileAttributes.ReparsePoint) != 0) throw new InvalidDataException("package.link-not-allowed");
                if (result.Count >= 8192) throw new InvalidDataException("package.too-many-files");
                result.Add(path);
                if ((attributes & FileAttributes.Directory) != 0) pending.Push(path);
            }
        }
        return result.ToArray();
    }

    internal static Dictionary<string, ZipArchiveEntry> Inspect(ZipArchive archive)
    {
        if (archive.Entries.Count > 4096) throw new InvalidDataException("package.too-many-files");
        long total = 0;
        var names = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        var result = new Dictionary<string, ZipArchiveEntry>(StringComparer.Ordinal);
        foreach (var entry in archive.Entries)
        {
            bool directory = entry.FullName.EndsWith('/');
            string name = directory ? entry.FullName[..^1] : entry.FullName;
            PluginApi.ValidatePath(name);
            if (!names.Add(name) || (entry.ExternalAttributes >> 16 & 0xf000) == 0xa000)
                throw new InvalidDataException("package.duplicate-or-link");
            total = checked(total + entry.Length);
            if (total > MaxExpandedBytes || directory && entry.Length != 0) throw new InvalidDataException("package.expanded-too-large");
            if (!directory) result.Add(name, entry);
        }
        return result;
    }

    private static byte[] Read(ZipArchiveEntry entry, int limit)
    {
        if (entry.Length > limit) throw new InvalidDataException("package.metadata-too-large");
        using var input = entry.Open(); using var output = new MemoryStream();
        byte[] buffer = new byte[8192]; int read;
        while ((read = input.Read(buffer)) != 0)
        {
            if (output.Length + read > limit) throw new InvalidDataException("package.metadata-too-large");
            output.Write(buffer, 0, read);
        }
        return output.ToArray();
    }
}
